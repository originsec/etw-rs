use etw::{Guid, Trace, provider_schema};
use example_providers::user::dotnet_runtime;

// Generated by `generate-provider Microsoft-Windows-DotNETRuntime --event-only 20`.
//
// Declared here rather than in `example-providers` because that crate is
// generated with `--provider-only` and carries no static schemas. The point of
// having it in *this* file is that the static parser and the dynamic parser then
// meet on the same real record: the static one takes its offsets from
// compile-time constants chosen by the event's bitness flag, the dynamic one
// from the TDH schema. Neither derives from the other, so agreement on a genuine
// 32-bit record is evidence about the generated `OFFSET_32` values rather than a
// restatement of them.
provider_schema! {
    guid: Guid::from_u128(0xe13c0d23_ccbc_4e12_931b_d9cc2eee27e4),
    events: {
        event { // GC [GCSampledObjectAllocationHighKeyword]
            id: 20,
            name: "GC",
            version { 0, fields: {
                Address: usize @ tdh(Pointer), // [0] Pointer
                TypeID: usize @ tdh(Pointer),  // [1] Pointer
                ObjectCountForTypeSample: u32, // [2] UInt32
                TotalSizeForTypeSample: u64,   // [3] UInt64
                ClrInstanceID: u16,            // [4] UInt16
            }}
        }
    }
}
use serial_test::serial;
use std::{
    process::{Child, Command},
    sync::{
        Arc, Mutex,
        atomic::{AtomicBool, AtomicU32, AtomicUsize, Ordering},
    },
    time::{Duration, Instant},
};

const PS_X64: &str = r"C:\Windows\System32\WindowsPowerShell\v1.0\powershell.exe";
const PS_X86: &str = r"C:\Windows\SysWOW64\WindowsPowerShell\v1.0\powershell.exe";

/// A shared bound would let one child's delivery volume starve the other.
const MAX_SAMPLES_PER_CHILD: usize = 10_000;
/// Upper bound on waiting for both of our processes to be represented.
const COLLECT_TIMEOUT: Duration = Duration::from_secs(40);

/// Allocation loop that reliably crosses the GC sampling threshold. The leading
/// sleep gives the harness time to finish spawning both children and wiring the
/// callback before either starts allocating.
fn alloc_command(delay_ms: u32) -> String {
    format!(
        "Start-Sleep -Milliseconds {delay_ms}; \
         for ($j = 0; $j -lt 40; $j++) {{ \
             $a = New-Object 'byte[]' 1MB; \
             [GC]::Collect(); \
         }}"
    )
}

fn spawn_ps(exe: &str, delay_ms: u32) -> Child {
    Command::new(exe)
        .args(["-NoProfile", "-Command", &alloc_command(delay_ms)])
        .spawn()
        .unwrap_or_else(|e| panic!("failed to launch {exe}: {e}"))
}

/// The only `GC` event version the `provider_schema!` above declares.
///
/// `GCParser` routes any other version to the dynamic parser, so `check` asserts
/// on this rather than trusting that the static path ran.
const STATIC_SCHEMA_VERSION: u8 = 0;

/// One parsed `GCSampledObjectAllocationHigh`, read through the generated parser.
///
/// Generic over the accessor trait rather than taking `GCParser` concretely, so it
/// reads the same way whichever version the parser resolved to.
fn read_via_static_parser<'a>(
    parser: &mut impl GCAccessors<'a>,
) -> etw::Result<(usize, usize, u32, u64, u16)> {
    Ok((
        parser.Address()?,
        parser.TypeID()?,
        parser.ObjectCountForTypeSample()?,
        parser.TotalSizeForTypeSample()?,
        parser.ClrInstanceID()?,
    ))
}

#[derive(Debug, Clone, Copy)]
struct Sample {
    pid: u32,
    is_32bit: bool,
    /// Event version, recorded so `check` can prove the static parser was really
    /// exercised rather than quietly replaced by the dynamic one.
    version: u8,
    address: usize,
    type_id: usize,
    object_count: u32,
    total_size: u64,
    clr_instance_id: u16,
}

/// Why the callback discarded an event, tallied per child as `[x86, x64]`:
/// `gated` was held by the priming order, `capped` was over budget.
#[derive(Default)]
struct Drops {
    gated: [AtomicU32; 2],
    capped: [AtomicU32; 2],
}

struct Run {
    samples: Vec<Sample>,
    errors: u32,
    /// Events where the generated static parser disagreed with the dynamic one,
    /// or failed where it succeeded. Counted rather than asserted in the
    /// callback, for the reason given in the module docs.
    static_mismatches: u32,
    drops: Arc<Drops>,
    x86_pid: u32,
    x64_pid: u32,
    /// Which bitness the callback gate held the cache open for.
    first_is_32bit: bool,
    /// Bitness of the first event 20 actually parsed — the one that populated
    /// the cache. Must match `first_is_32bit`.
    first_seen_32bit: Option<bool>,
}

/// Run one session with both bitnesses emitting, the given one reaching the
/// schema cache first.
///
/// `None` means the host lacked privilege to trace.
fn run_session(session: &str, first_is_32bit: bool) -> Option<Run> {
    const START_DELAY_MS: u32 = 500;
    let mut trace = Trace::new(session).expect("create trace");
    common::skip_or_panic("trace.start", trace.start())?;

    // Event 20 needs the GC sampled-allocation keyword on top of GCKEYWORD.
    trace
        .enable_provider(
            dotnet_runtime::GUID,
            dotnet_runtime::keyword::GCKEYWORD | 0x20_0000,
        )
        .expect("enable DotNETRuntime");

    let samples: Arc<Mutex<Vec<Sample>>> = Arc::new(Mutex::new(Vec::new()));
    let errors = Arc::new(AtomicU32::new(0));
    let drops = Arc::new(Drops::default());

    // Spawn before wiring the callback so it can scope to our own PIDs. Both
    // children sleep before allocating, so nothing is missed in the meantime.
    let mut x86 = spawn_ps(PS_X86, START_DELAY_MS);
    let mut x64 = spawn_ps(PS_X64, START_DELAY_MS);
    let x86_pid = x86.id();
    let x64_pid = x64.id();
    println!("[{session}] x86 pid={x86_pid} x64 pid={x64_pid}");

    // Moved into the callback; nothing outside reads them.
    let primed = AtomicBool::new(false);
    // Per-child counts, `[x86, x64]` — an O(1) read instead of scanning
    // `samples`, which grows into the thousands.
    let accepted: [AtomicUsize; 2] = Default::default();
    let static_mismatches = Arc::new(AtomicU32::new(0));
    let samples_cb = samples.clone();
    let errors_cb = errors.clone();
    let static_cb = static_mismatches.clone();
    let drops_cb = drops.clone();
    trace.set_event_callback(move |event, context| {
        if event.provider_guid() != dotnet_runtime::GUID || event.id() != 20 {
            return Ok(());
        }
        // An ambient .NET event from another process could otherwise
        // populate the cache before our priming gate gets a say.
        let pid = event.process_id();
        if pid != x86_pid && pid != x64_pid {
            return Ok(());
        }
        let child = usize::from(pid == x64_pid);
        if accepted[child].load(Ordering::Relaxed) >= MAX_SAMPLES_PER_CHILD {
            drops_cb.capped[child].fetch_add(1, Ordering::Relaxed);
            return Ok(());
        }

        let is_32bit = (event.as_raw().EventHeader.Flags
            & windows::Win32::System::Diagnostics::Etw::EVENT_HEADER_FLAG_32_BIT_HEADER as u16)
            != 0;

        // Timing can't pick the order — both PowerShells JIT before reaching
        // their sleep, so x64's event 20 always arrives first regardless of
        // any stagger.
        if !primed.load(Ordering::Relaxed) && is_32bit != first_is_32bit {
            drops_cb.gated[child].fetch_add(1, Ordering::Relaxed);
            return Ok(());
        }

        // Field reads are collected into a Result rather than `?`-ed straight out
        // of the callback: propagating would skip the counter, leaving the
        // `errors == 0` assertion passing while individual properties failed to
        // parse — exactly the failure this test exists to catch.
        let parsed = context.parser(event).and_then(|mut parser| {
            Ok(Sample {
                pid: event.process_id(),
                is_32bit,
                version: event.as_raw().EventHeader.EventDescriptor.Version,
                address: parser.get("Address")?,
                type_id: parser.get("TypeID")?,
                object_count: parser.get("ObjectCountForTypeSample")?,
                total_size: parser.get("TotalSizeForTypeSample")?,
                clr_instance_id: parser.get("ClrInstanceID")?,
            })
        });

        // Same record, through the generated static parser. `GCParser::new` picks
        // the version and derives the pointer width from the event's header
        // flags, which is the production path; `from_bytes_with_pointer_size`
        // would bypass exactly the step under test.
        let statik = GCParser::new(event, context).and_then(|mut p| read_via_static_parser(&mut p));

        match parsed {
            Ok(sample) => {
                let agrees = matches!(
                    statik,
                    Ok((address, type_id, object_count, total_size, clr_instance_id))
                        if address == sample.address
                            && type_id == sample.type_id
                            && object_count == sample.object_count
                            && total_size == sample.total_size
                            && clr_instance_id == sample.clr_instance_id
                );
                if !agrees {
                    static_cb.fetch_add(1, Ordering::Relaxed);
                }
                samples_cb.lock().unwrap().push(sample);
                accepted[child].fetch_add(1, Ordering::Relaxed);
                primed.store(true, Ordering::Relaxed);
            }
            Err(_) => {
                errors_cb.fetch_add(1, Ordering::Relaxed);
            }
        }
        Ok(())
    });

    trace
        .set_processing_thread_startup_timeout(500)
        .start_processing_thread()
        .expect("start processing");

    // Stop once both of our processes are represented; the interaction is the
    // point, not the volume.
    let deadline = Instant::now() + COLLECT_TIMEOUT;
    while Instant::now() < deadline {
        std::thread::sleep(Duration::from_millis(200));
        let s = samples.lock().unwrap();
        if s.iter().any(|x| x.pid == x86_pid) && s.iter().any(|x| x.pid == x64_pid) {
            break;
        }
    }

    let _ = x86.wait();
    let _ = x64.wait();
    trace.stop().expect("stop session");

    let out = samples.lock().unwrap().clone();
    let first_seen_32bit = out.first().map(|s| s.is_32bit);
    Some(Run {
        samples: out,
        errors: errors.load(Ordering::Relaxed),
        static_mismatches: static_mismatches.load(Ordering::Relaxed),
        drops,
        x86_pid,
        x64_pid,
        first_is_32bit,
        first_seen_32bit,
    })
}

/// Every invariant that holds only if the pointer width was resolved per event.
fn check(label: &str, run: &Run) {
    let from_x86: Vec<_> = run
        .samples
        .iter()
        .filter(|s| s.pid == run.x86_pid)
        .collect();
    let from_x64: Vec<_> = run
        .samples
        .iter()
        .filter(|s| s.pid == run.x64_pid)
        .collect();
    println!(
        "[{label}] total={} from_x86={} from_x64={} errors={} first_seen_32bit={:?}",
        run.samples.len(),
        from_x86.len(),
        from_x64.len(),
        run.errors,
        run.first_seen_32bit
    );
    println!(
        "[{label}] dropped gated=[x86 {} x64 {}] capped=[x86 {} x64 {}]",
        run.drops.gated[0].load(Ordering::Relaxed),
        run.drops.gated[1].load(Ordering::Relaxed),
        run.drops.capped[0].load(Ordering::Relaxed),
        run.drops.capped[1].load(Ordering::Relaxed),
    );

    assert_eq!(run.errors, 0, "[{label}] {} parse errors", run.errors);

    // The generated static parser must agree with the TDH-driven dynamic parser
    // on every event, in both bitnesses. They compute offsets independently --
    // compile-time constants selected by the header's bitness flag on one side,
    // the TDH schema on the other -- so a disagreement means the generated
    // `OFFSET_32`/`OFFSET_64` constants are wrong for a real manifest. The
    // synthetic tests in `static_schema_pointer_size.rs` cannot catch that,
    // because there the same declaration produces both the offsets and the
    // expectations.
    // `gc_dispatch!` hands the handler a *dynamic* parser for any version above
    // the one the schema declares, and that parser implements the same accessor
    // trait. So if .NET emits a `GC` version this schema does not cover, the
    // comparison below is the dynamic parser against itself: it passes while
    // testing nothing. Fail loudly instead, so the symptom is "regenerate the
    // schema" rather than a green test that quietly stopped checking.
    let unknown: Vec<u8> = run
        .samples
        .iter()
        .map(|s| s.version)
        .filter(|&v| v != STATIC_SCHEMA_VERSION)
        .collect();
    assert!(
        unknown.is_empty(),
        "[{label}] {} of {} events carried a GC version outside the static schema (first {:?}, schema declares {STATIC_SCHEMA_VERSION}); the static-parser comparison would have compared the dynamic parser with itself",
        unknown.len(),
        run.samples.len(),
        unknown.first()
    );

    assert_eq!(
        run.static_mismatches,
        0,
        "[{label}] static parser disagreed with the dynamic parser on {} of {} events",
        run.static_mismatches,
        run.samples.len()
    );

    // The callback gate makes this exact, so assert it: if the intended bitness
    // did not populate the cache, this run tested the other direction twice.
    assert_eq!(
        run.first_seen_32bit,
        Some(run.first_is_32bit),
        "[{label}] cache was populated by the wrong bitness first"
    );

    // Both of our own processes must be represented, or the session never had
    // two bitnesses in one cache and a pass would mean nothing.
    assert!(
        !from_x86.is_empty(),
        "[{label}] no events from our 32-bit process (pid {}) — mixed-bitness caching not exercised",
        run.x86_pid
    );
    assert!(
        !from_x64.is_empty(),
        "[{label}] no events from our 64-bit process (pid {}) — mixed-bitness caching not exercised",
        run.x64_pid
    );

    // Header bitness must match the process we launched.
    assert!(
        from_x86.iter().all(|s| s.is_32bit),
        "[{label}] events from the 32-bit process were not flagged 32-bit"
    );
    assert!(
        from_x64.iter().all(|s| !s.is_32bit),
        "[{label}] events from the 64-bit process were flagged 32-bit"
    );

    for s in &run.samples {
        if s.is_32bit {
            // A 4-byte Pointer read cannot exceed u32::MAX. Exceeding it means
            // the field was sized using the 64-bit offsets.
            assert!(
                u32::try_from(s.address).is_ok(),
                "[{label}] pid {} 32-bit Address read wider than 4 bytes: 0x{:X}",
                s.pid,
                s.address
            );
            assert!(
                u32::try_from(s.type_id).is_ok(),
                "[{label}] pid {} 32-bit TypeID read wider than 4 bytes: 0x{:X}",
                s.pid,
                s.type_id
            );
        }

        // These sit after the Pointer fields, so they decode from the wrong
        // bytes if the preceding pointer width was wrong — in either direction.
        // This is what catches a 32-bit-populated cache corrupting 64-bit reads,
        // where the u32 bound above cannot help.
        assert!(
            s.object_count >= 1,
            "[{label}] pid {} ObjectCountForTypeSample={} (is_32bit={}) — offsets misaligned",
            s.pid,
            s.object_count,
            s.is_32bit
        );
        // Corrupted offsets read these out of pointer bytes, which are huge;
        // the real values are small. This is what catches the 32-bit-first
        // direction, where a truncated 8-byte pointer shifts every later field
        // without ever running off the end of the payload or erroring.
        assert!(
            s.object_count < 1_000_000,
            "[{label}] pid {} ObjectCountForTypeSample={} (is_32bit={}) — reads like pointer bytes, offsets misaligned",
            s.pid,
            s.object_count,
            s.is_32bit
        );
        assert!(
            s.clr_instance_id < 1024,
            "[{label}] pid {} ClrInstanceID={} (is_32bit={}) — offsets misaligned",
            s.pid,
            s.clr_instance_id,
            s.is_32bit
        );
        assert!(
            s.total_size >= u64::from(s.object_count),
            "[{label}] pid {} TotalSizeForTypeSample={} < ObjectCount={} (is_32bit={}) — offsets misaligned",
            s.pid,
            s.total_size,
            s.object_count,
            s.is_32bit
        );
    }
}

fn require_powershells() {
    assert!(
        std::path::Path::new(PS_X86).exists(),
        "32-bit PowerShell not found at {PS_X86}"
    );
    assert!(
        std::path::Path::new(PS_X64).exists(),
        "64-bit PowerShell not found at {PS_X64}"
    );
}

/// Biased so 64-bit events populate the schema cache first; 32-bit reads must
/// not inherit the 8-byte offsets.
#[test]
#[serial(mixed_bitness)]
fn test_mixed_bitness_64bit_populates_cache_first() {
    require_powershells();
    let Some(run) = run_session("etw-rs_Test_MixedBitness_64First", false) else {
        return; // insufficient privilege — skip
    };
    check("64-bit first", &run);
}

/// The reverse bias: 32-bit first, so 64-bit reads must not inherit the 4-byte
/// offsets. One direction alone cannot catch cache poisoning.
#[test]
#[serial(mixed_bitness)]
fn test_mixed_bitness_32bit_populates_cache_first() {
    require_powershells();
    let Some(run) = run_session("etw-rs_Test_MixedBitness_32First", true) else {
        return; // insufficient privilege — skip
    };
    check("32-bit first", &run);
}

//! Static schema code generation from TDH metadata.
//!
//! Generates complete provider modules with NAME, GUID, keywords, event IDs,
//! and `provider_schema!` static schemas from the operating system's manifest data.
//!
//! Used by the `generate-provider` binary and available for programmatic use.

use crate::{
    manifest::{
        EventFieldInfo, PROPERTY_PARAM_COUNT, PROPERTY_PARAM_LENGTH, PROPERTY_STRUCT,
        ProviderEventInfo, ProviderFieldInfo, event_name_to_rust, get_best_event_name,
        get_event_fields, get_event_keyword_name, keyword_name_to_rust,
    },
    mof::{MofProvider, get_mof_event_fields, get_mof_event_name, strip_version_suffix},
};
use etw::system_logger::{masks::guid_to_perf_masks, stack_walk::guid_to_group_id};
use std::{
    collections::{HashMap, HashSet},
    fmt::Write as _,
};
use windows::core::GUID;

/// Maps `(class_key, event_id, version)` to a Windows release string.
///
/// - For manifest providers, `class_key` is `""`.
/// - For MOF providers, `class_key` is the lowercased class GUID without braces.
pub type ReleaseMap = HashMap<(String, u16, u8), String>;


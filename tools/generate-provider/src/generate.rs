/// Writes a "To regenerate" comment line to `out`.
///
/// ```text
/// // generate-provider <provider> <flags>
/// ```
#[expect(clippy::unwrap_used, reason = "write! to String is infallible")]
fn write_regenerate_comment(out: &mut String, command: &str) {
    writeln!(out, "// {command}").unwrap();
}


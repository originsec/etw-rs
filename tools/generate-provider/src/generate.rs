/// Result of resolving fields for a single event version.
enum FieldResolution {
    /// Event has no fields at all.
    NoFields,
    /// Fields resolved — some may be emittable, with unsupported trailing
    /// fields captured as comment strings.
    Resolved {
        emittable: Vec<ResolvedField>,
        commented: Vec<String>,
    },
}

/// Resolves fields for a single event version, returning emittable fields and
/// comment lines for unsupported trailing fields.
///
/// Fields are resolved in order. Once an unsupported field is encountered, all
/// remaining fields are captured as comment lines, since the static schema
/// parser reads fields sequentially and cannot skip gaps.
fn resolve_fields(fields: &[EventFieldInfo]) -> FieldResolution {
    if fields.is_empty() {
        return FieldResolution::NoFields;
    }

    let mut emittable = Vec::new();
    let mut commented = Vec::new();
    let mut hit_unsupported = false;

    for (index, field) in fields.iter().enumerate() {
        let name = sanitise_field_name(&field.name);

        if hit_unsupported {
            if (field.flags & PROPERTY_PARAM_COUNT) != 0 {
                // Counted array in the unsupported tail
                let element_type = intype_to_rust_type(field, fields)
                    .unwrap_or_else(|| format!("InType {}", field.in_type));
                commented.push(format!("[{index}] {name}: [{element_type}]"));
            } else if let Some(rt) = intype_to_rust_type(field, fields) {
                commented.push(format!("[{index}] {name}: {rt}"));
            } else {
                commented.push(format!("[{index}] {name} (InType {})", field.in_type));
            }
            continue;
        }

        // Nested struct properties
        if (field.flags & PROPERTY_STRUCT) != 0 {
            let has_param_count = (field.flags & PROPERTY_PARAM_COUNT) != 0;
            let type_label = if has_param_count {
                "Struct[]".to_owned()
            } else {
                "Struct".to_owned()
            };
            match (field.struct_byte_size, has_param_count) {
                (Some(size), false) => {
                    // Non-counted struct — emit as fixed_length binary blob
                    emittable.push(ResolvedField {
                        name,
                        rust_type: format!("u8 @ fixed_length({size})"),
                        index,
                        in_type_name: type_label,
                    });
                }
                (Some(size), true) => {
                    // Counted struct array — emit as count_bytes
                    if let Some(idx) = field.count_property_index
                        && let Some(cf) = fields.get(idx as usize)
                    {
                        let cf_name = sanitise_field_name(&cf.name);
                        emittable.push(ResolvedField {
                            name,
                            rust_type: format!("u8 @ count_bytes(\"{cf_name}\", {size})"),
                            index,
                            in_type_name: type_label,
                        });
                        continue;
                    }
                    hit_unsupported = true;
                    commented.push(format!(
                        "[{index}] {name} (counted struct, missing count field)"
                    ));
                }
                (None, _) => {
                    // Variable-length struct members — cannot compute byte size
                    hit_unsupported = true;
                    commented.push(format!(
                        "[{index}] {name} (struct with variable-length members)"
                    ));
                }
            }
            continue;
        }

        // Variable-count array
        if (field.flags & PROPERTY_PARAM_COUNT) != 0 {
            let array_type_name = format!("{}[]", intype_name(field.in_type));
            if let Some(count_idx) = field.count_property_index
                && let Some(count_field) = fields.get(count_idx as usize)
            {
                let count_field_name = sanitise_field_name(&count_field.name);
                if let Some(scalar_type) = intype_to_scalar_type(field.in_type) {
                    emittable.push(ResolvedField {
                        name,
                        rust_type: format!("{scalar_type} @ count(\"{count_field_name}\")"),
                        index,
                        in_type_name: array_type_name,
                    });
                    continue;
                }
            }
            // Fall through to unsupported — variable-length elements can't use simple count*size
            hit_unsupported = true;
            let element_type = intype_to_rust_type(field, fields)
                .unwrap_or_else(|| format!("InType {}", field.in_type));
            commented.push(format!(
                "[{index}] {name}: [{element_type}] (variable-count variable-element-length array)"
            ));
            continue;
        }

        if let Some(rt) = intype_to_rust_type(field, fields) {
            let rust_type = match tdh_annotation(field.in_type) {
                Some(tdh) => format!("{rt} @ tdh({tdh})"),
                None => rt,
            };
            emittable.push(ResolvedField {
                name,
                rust_type,
                index,
                in_type_name: intype_name(field.in_type).to_owned(),
            });
        } else {
            hit_unsupported = true;
            commented.push(format!("[{index}] {name} (InType {})", field.in_type));
        }
    }

    FieldResolution::Resolved {
        emittable,
        commented,
    }
}

/// TDH in-types a Rust type cannot distinguish, so the schema has to name them.
///
/// `u64` covers UInt64, FileTime and HexInt64; `usize` covers Pointer and SizeT.
/// `provider_schema!` assumes the first member of each group, so every other member
/// needs an explicit `@ tdh(...)` for the accessor doc to be accurate and for
/// `validate_schema` to compare exactly rather than by compatibility group.
const fn tdh_annotation(in_type: u16) -> Option<&'static str> {
    match in_type {
        16 => Some("Pointer"),
        17 => Some("FileTime"),
        20 => Some("HexInt32"),
        21 => Some("HexInt64"),
        306 => Some("UnicodeChar"),
        307 => Some("AnsiChar"),
        _ => None,
    }
}

/// Maps a TDH InType to the corresponding Rust type string for `provider_schema!`.
///
/// Returns the type string including any `@ length("X")` annotation for binary fields.
fn intype_to_rust_type(field: &EventFieldInfo, all_fields: &[EventFieldInfo]) -> Option<String> {
    // Length specified by another field
    let has_param_length = (field.flags & PROPERTY_PARAM_LENGTH) != 0;

    match field.in_type {
        1 => Some("WideStrRef".to_owned()),     // UnicodeString
        2 => Some("AnsiStrRef".to_owned()),     // AnsiString
        3 => Some("i8".to_owned()),             // Int8
        4 => Some("u8".to_owned()),             // UInt8
        5 => Some("i16".to_owned()),            // Int16
        6 => Some("u16".to_owned()),            // UInt16
        7 => Some("i32".to_owned()),            // Int32
        8 | 20 => Some("u32".to_owned()),       // UInt32, HexInt32
        9 => Some("i64".to_owned()),            // Int64
        10 | 17 | 21 => Some("u64".to_owned()), // UInt64, FileTime, HexInt64
        11 => Some("f32".to_owned()),           // Float
        12 => Some("f64".to_owned()),           // Double
        13 => Some("bool".to_owned()),          // Boolean
        14 => {
            // Binary — try param length first, then fixed length from property info
            if has_param_length {
                if let Some(idx) = field.length_property_index {
                    let length_field = all_fields.get(idx as usize)?;
                    let length_name = sanitise_field_name(&length_field.name);
                    Some(format!("u8 @ length(\"{length_name}\")"))
                } else {
                    None
                }
            } else if field.length > 0 {
                // Fixed byte length from EVENT_PROPERTY_INFO
                Some(format!("u8 @ fixed_length({})", field.length))
            } else {
                None
            }
        }
        15 => Some("Guid".to_owned()),        // GUID
        16 | 308 => Some("usize".to_owned()), // Pointer, SizeT (WBEM)
        18 => Some("SystemTime".to_owned()),  // SystemTime
        19 => Some("SidRef".to_owned()),      // SID
        306 => {
            // UnicodeChar — single WCHAR or fixed-length WCHAR array
            let byte_len = field.effective_byte_length(2);
            if byte_len <= 2 {
                Some("u16".to_owned())
            } else {
                Some(format!("u8 @ fixed_length({byte_len})"))
            }
        }
        307 => {
            // AnsiChar — single byte or fixed-length CHAR array
            let byte_len = field.effective_byte_length(1);
            if byte_len <= 1 {
                Some("u8".to_owned())
            } else {
                Some(format!("u8 @ fixed_length({byte_len})"))
            }
        }
        310 => Some("WbemSidRef".to_owned()), // WbemSid (TOKEN_USER + SID)
        22 => Some("CountedWideStrRef".to_owned()), // ManifestCountedString
        23 => Some("CountedAnsiStrRef".to_owned()), // ManifestCountedAnsiString
        25 => Some("CountedBinaryRef".to_owned()), // ManifestCountedBinary
        _ => None,
    }
}

/// Maps a TDH InType to the corresponding Rust scalar type name for counted arrays.

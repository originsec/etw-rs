/// Generates the `provider_schema!` block for a MOF provider.
///
/// Each unique `(class_guid, opcode)` combination becomes an event block,
/// with versions nested inside. Emits `opcode:` instead of `id:` so runtime
/// debug assertions check `event.opcode()` rather than `event.id()`.
///
/// When `multi_class` is true, class GUIDs are emitted as references to the
/// `class_guid` module (e.g., `class_guid: class_guid::ALPC,`). Otherwise,
/// they are emitted inline as `Guid::from_u128(0x...)`.
///
/// `extra_flags` is appended to the "To regenerate" comment (e.g. `" --event-only 10"`).
#[expect(clippy::unwrap_used, reason = "write! to String is infallible")]
#[expect(
    clippy::too_many_arguments,
    reason = "internal generator with many orthogonal options"
)]
fn generate_mof_schema_block(
    unique_events: &[&crate::mof::MofEventClass],
    display_name: &str,
    provider_guid: &GUID,
    multi_class: bool,
    class_guid_names: &HashMap<u128, String>,
    extra_flags: &str,
    releases: Option<&ReleaseMap>,
    drop_old: bool,
) -> String {
    // Group by (class_guid, opcode), then collect versions
    let mut groups: Vec<MofEventGroup> = Vec::new();
    for ev in unique_events {
        let existing = groups.iter_mut().find(|g| {
            guid_to_u128(&g.class_guid) == guid_to_u128(&ev.class_guid) && g.opcode == ev.opcode
        });
        if let Some(group) = existing {
            group
                .versions
                .push((ev.version, ev.event_type_name.clone()));
        } else {
            groups.push(MofEventGroup {
                class_guid: ev.class_guid,
                class_name: ev.class_name.clone(),
                opcode: ev.opcode,
                versions: vec![(ev.version, ev.event_type_name.clone())],
            });
        }
    }
    groups.sort_by(|a, b| {
        let name_a = strip_version_suffix(&a.class_name).to_lowercase();
        let name_b = strip_version_suffix(&b.class_name).to_lowercase();
        name_a.cmp(&name_b).then(a.opcode.cmp(&b.opcode))
    });

    let is_event_only = extra_flags.contains("--event-only");

    let mut output = String::new();
    if is_event_only {
        writeln!(
            output,
            "// BEGIN Auto-generated by etw-rs generate-provider (MOF)."
        )
        .unwrap();
    } else {
        writeln!(
            output,
            "// Auto-generated by etw-rs generate-provider (MOF)."
        )
        .unwrap();
    }
    write_regenerate_comment(
        &mut output,
        &format!(
            "generate-provider \"{display_name}\"{}{extra_flags}",
            if is_event_only { "" } else { " --schema-only" }
        ),
    );
    writeln!(output, "etw::provider_schema! {{").unwrap();
    if is_event_only {
        let guid_literal = format_guid_u128(guid_to_u128(provider_guid));
        writeln!(output, "    guid: Guid::from_u128(0x{guid_literal}),").unwrap();
    } else {
        writeln!(output, "    guid: GUID,").unwrap();
    }
    writeln!(output, "    events: {{").unwrap();

    let mut first_event = true;
    let mut used_parser_names: HashSet<String> = HashSet::new();
    let mut current_class: Option<u128> = None;

    for group in &groups {
        // Emit class header when the class GUID changes (skip for --event-only).
        let class_key = guid_to_u128(&group.class_guid);
        if current_class != Some(class_key) {
            current_class = Some(class_key);
            if !is_event_only {
                if !first_event {
                    writeln!(output).unwrap();
                }
                let class_label = if group.class_name.is_empty() {
                    format!("{class_key:032x}")
                } else {
                    strip_version_suffix(&group.class_name).to_owned()
                };
                writeln!(
                    output,
                    "        // ============================================="
                )
                .unwrap();
                writeln!(output, "        // {class_label}").unwrap();
                writeln!(
                    output,
                    "        // ============================================="
                )
                .unwrap();
                first_event = false;
            }
        }

        // Sort versions
        let mut versions = group.versions.clone();
        versions.sort_by_key(|(v, _)| *v);

        let event_name = get_mof_event_name(&group.class_guid, group.opcode, versions[0].0);
        let type_name = &versions[0].1;

        // Raw TDH name (for inline comments and skip messages)
        let raw_name = event_name
            .as_deref()
            .or_else(|| (!type_name.is_empty()).then_some(type_name.as_str()));
        let name_str = raw_name.unwrap_or("unknown");

        // Parser name: sanitise → normalise class prefix → fallback to class+Opcode{N}
        let parser_display = raw_name.map_or_else(
            || {
                let prefix = class_prefix(&group.class_name);
                format!("{prefix}Opcode{}", group.opcode)
            },
            |n| normalize_mof_event_name(&sanitise_parser_name(n), &group.class_name),
        );

        let mut emitted_versions: Vec<VersionOutput> = Vec::new();
        let mut skipped: Vec<String> = Vec::new();

        for (version, _name) in &versions {
            let fields = match get_mof_event_fields(&group.class_guid, group.opcode, *version) {
                Ok(f) => f,
                Err(e) => {
                    skipped.push(format!("// Skipped v{version}: error querying fields: {e}"));
                    continue;
                }
            };

            match resolve_fields(&fields) {
                FieldResolution::NoFields => {
                    skipped.push(format!(
                        "// {name_str} (opcode {}, v{version}): no fields",
                        group.opcode
                    ));
                }
                FieldResolution::Resolved {
                    emittable,
                    commented,
                } => {
                    if emittable.is_empty() {
                        let field_list: String = commented.join(", ");
                        skipped.push(format!(
                            "// Skipped v{version}: all fields unsupported — {field_list}"
                        ));
                        continue;
                    }

                    // Check if previous emitted version is an exact prefix
                    let extends = emitted_versions.last().and_then(|prev| {
                        (prev.resolved.len() <= emittable.len()
                            && prev
                                .resolved
                                .iter()
                                .zip(&emittable)
                                .all(|(p, c)| p.name == c.name && p.rust_type == c.rust_type))
                        .then_some(prev.version)
                    });

                    emitted_versions.push(VersionOutput {
                        version: *version,
                        extends,
                        resolved: emittable,
                        commented,
                    });
                }
            }
        }

        // Drop old versions not present in the release dataset, unless
        // they have identical fields to an adjacent kept version.
        if drop_old {
            let class_guid_str = format_guid_lowercase(&group.class_guid);
            let kept: Vec<bool> = emitted_versions
                .iter()
                .map(|v| {
                    should_keep_version(
                        releases,
                        &class_guid_str,
                        u16::from(group.opcode),
                        v.version,
                    )
                })
                .collect();
            let mut retain = kept.clone();
            for (i, is_kept) in kept.iter().enumerate() {
                if !is_kept {
                    let fields_match = |a: &[ResolvedField], b: &[ResolvedField]| {
                        a.len() == b.len()
                            && a.iter()
                                .zip(b)
                                .all(|(x, y)| x.name == y.name && x.rust_type == y.rust_type)
                    };
                    let adj_match = (i > 0
                        && kept[i - 1]
                        && fields_match(
                            &emitted_versions[i].resolved,
                            &emitted_versions[i - 1].resolved,
                        ))
                        || (i + 1 < kept.len()
                            && kept[i + 1]
                            && fields_match(
                                &emitted_versions[i].resolved,
                                &emitted_versions[i + 1].resolved,
                            ));
                    retain[i] = adj_match;
                }
            }
            let mut idx = 0;
            emitted_versions.retain(|_| {
                let keep = retain[idx];
                idx += 1;
                keep
            });

            // Clear stale `extends` references to dropped versions.
            let remaining: HashSet<u8> = emitted_versions.iter().map(|v| v.version).collect();
            for v in &mut emitted_versions {
                if v.extends.is_some_and(|base| !remaining.contains(&base)) {
                    v.extends = None;
                }
            }
        }

        if emitted_versions.is_empty() && skipped.is_empty() {
            continue;
        }

        if !first_event {
            writeln!(output).unwrap();
        }
        first_event = false;

        // Build inline comment from the raw TDH name
        let inline_comment = raw_name.map(|s| format!(" // {s}")).unwrap_or_default();

        if emitted_versions.is_empty() {
            for s in &skipped {
                writeln!(output, "        {s}").unwrap();
            }
            continue;
        }

        // Parser name from normalised display name
        let parser_name = if used_parser_names.contains(&parser_display) {
            format!("{parser_display}{}", group.opcode)
        } else {
            parser_display.clone()
        };
        used_parser_names.insert(parser_name.clone());

        writeln!(output, "        event {{{inline_comment}").unwrap();
        writeln!(output, "            opcode: {},", group.opcode).unwrap();
        writeln!(output, "            name: \"{parser_name}\",").unwrap();

        // Emit class_guid for TDH validation (MOF events use class GUID, not provider GUID)
        let class_key = guid_to_u128(&group.class_guid);
        if multi_class {
            if let Some(const_name) = class_guid_names.get(&class_key) {
                writeln!(output, "            class_guid: class_guid::{const_name},").unwrap();
            }
        } else {
            let class_guid_literal = format_guid_u128(class_key);
            writeln!(
                output,
                "            class_guid: Guid::from_u128(0x{class_guid_literal}),"
            )
            .unwrap();
        }

        for s in &skipped {
            writeln!(output, "            {s}").unwrap();
        }

        for ver in &emitted_versions {
            let fields_to_emit;
            let mut header = format!("{}", ver.version);
            if let Some(base_ver) = ver.extends {
                let prefix_len = emitted_versions
                    .iter()
                    .find(|v| v.version == base_ver)
                    .map_or(0, |v| v.resolved.len());
                write!(header, ", extends_version: {base_ver}").unwrap();
                fields_to_emit = &ver.resolved[prefix_len..];
            } else {
                fields_to_emit = &ver.resolved[..];
            }

            if !ver.commented.is_empty() {
                write!(header, ", truncated: true").unwrap();
            }

            // Optionally annotate with the Windows release that introduced this version
            let class_guid_str = format_guid_lowercase(&group.class_guid);
            let release_comment = release_annotation(
                releases,
                &(class_guid_str, u16::from(group.opcode), ver.version),
            );

            writeln!(
                output,
                "            version {{ {header}, fields: {{{release_comment}"
            )
            .unwrap();
            let max_width = fields_to_emit
                .iter()
                .map(|f| f.name.len() + 2 + f.rust_type.len() + 1) // "name: type,"
                .max()
                .unwrap_or(0);
            for field in fields_to_emit {
                let field_part = format!("{}: {},", field.name, field.rust_type);
                writeln!(
                    output,
                    "                {:<width$} // [{}] {}",
                    field_part,
                    field.index,
                    field.in_type_name,
                    width = max_width
                )
                .unwrap();
            }
            for comment in &ver.commented {
                writeln!(output, "                // {comment}").unwrap();
            }
            writeln!(output, "            }}}}").unwrap();
        }

        writeln!(output, "        }}").unwrap();
    }

    writeln!(output, "    }}").unwrap();
    writeln!(output, "}}").unwrap();
    if is_event_only {
        writeln!(
            output,
            "// END Auto-generated by etw-rs generate-provider (MOF)."
        )
        .unwrap();
    }

    output
}


/// Generates a comment-only summary of event fields for a MOF provider.
///
/// Produces the same information as `generate_mof_schema` but rendered as
/// pure `//` comments with no compilable code.
#[expect(clippy::unwrap_used, reason = "write! to String is infallible")]
pub fn generate_mof_comment_block(
    provider: &MofProvider,
    display_name: Option<&str>,
    extra_flags: &str,
    releases: Option<&ReleaseMap>,
    drop_old: bool,
) -> String {
    let name = display_name.unwrap_or(&provider.name);

    // Deduplicate events by (class_guid, opcode, version)
    let mut seen = HashSet::new();
    let mut unique_events = Vec::new();
    for ev in &provider.events {
        let key = (guid_to_u128(&ev.class_guid), ev.opcode, ev.version);
        if seen.insert(key) {
            unique_events.push(ev);
        }
    }

    // Group by (class_guid, opcode), collect versions
    let mut groups: Vec<MofEventGroup> = Vec::new();
    for ev in &unique_events {
        let existing = groups.iter_mut().find(|g| {
            guid_to_u128(&g.class_guid) == guid_to_u128(&ev.class_guid) && g.opcode == ev.opcode
        });
        if let Some(group) = existing {
            group
                .versions
                .push((ev.version, ev.event_type_name.clone()));
        } else {
            groups.push(MofEventGroup {
                class_guid: ev.class_guid,
                class_name: ev.class_name.clone(),
                opcode: ev.opcode,
                versions: vec![(ev.version, ev.event_type_name.clone())],
            });
        }
    }
    groups.sort_by(|a, b| {
        let name_a = strip_version_suffix(&a.class_name).to_lowercase();
        let name_b = strip_version_suffix(&b.class_name).to_lowercase();
        name_a.cmp(&name_b).then(a.opcode.cmp(&b.opcode))
    });

    let mut output = String::new();

    writeln!(
        output,
        "// BEGIN Generated by etw-rs generate-provider (comment-only, MOF)."
    )
    .unwrap();
    write_regenerate_comment(
        &mut output,
        &format!("generate-provider \"{name}\"{extra_flags}"),
    );
    writeln!(output, "//").unwrap();

    for group in &groups {
        let mut versions = group.versions.clone();
        versions.sort_by_key(|(v, _)| *v);

        let event_name = get_mof_event_name(&group.class_guid, group.opcode, versions[0].0);
        let type_name = &versions[0].1;
        let raw_name = event_name
            .as_deref()
            .or_else(|| (!type_name.is_empty()).then_some(type_name.as_str()));
        let name_str = raw_name.unwrap_or("unknown");

        // Header
        writeln!(output, "// Event: {name_str} (opcode {})", group.opcode).unwrap();

        // Collect version field data
        let mut emitted_versions: Vec<CommentVersionOutput> = Vec::new();
        let mut skipped: Vec<String> = Vec::new();

        for (version, _name) in &versions {
            let fields = match get_mof_event_fields(&group.class_guid, group.opcode, *version) {
                Ok(f) => f,
                Err(e) => {
                    skipped.push(format!("// Skipped v{version}: error querying fields: {e}"));
                    continue;
                }
            };

            if fields.is_empty() {
                skipped.push(format!("// v{version}: no fields"));
                continue;
            }

            let comment_fields: Vec<CommentField> = fields
                .iter()
                .enumerate()
                .map(|(i, f)| CommentField {
                    index: i,
                    name: sanitise_field_name(&f.name),
                    in_type_name: intype_name(f.in_type).to_owned(),
                })
                .collect();

            // Detect prefix extension
            let extends = emitted_versions.last().and_then(|prev| {
                (prev.fields.len() <= comment_fields.len()
                    && prev
                        .fields
                        .iter()
                        .zip(&comment_fields)
                        .all(|(p, c)| p.name == c.name && p.in_type_name == c.in_type_name))
                .then_some(prev.version)
            });

            emitted_versions.push(CommentVersionOutput {
                version: *version,
                extends,
                fields: comment_fields,
            });
        }

        // Drop old versions not in the release dataset, unless they have
        // identical fields to an adjacent kept version.
        let class_guid_str = format_guid_lowercase(&group.class_guid);
        if drop_old {
            filter_old_comment_versions(
                &mut emitted_versions,
                releases,
                &class_guid_str,
                u16::from(group.opcode),
            );
        }

        // Collect TDH-known version numbers for release-only check
        let known_versions: HashSet<u8> = versions.iter().map(|(v, _)| *v).collect();

        // Versions only known from the release dataset (not on this OS)
        let extra = release_only_versions(
            releases,
            &class_guid_str,
            u16::from(group.opcode),
            &known_versions,
        );

        // Emit skipped versions
        for s in &skipped {
            writeln!(output, "{s}").unwrap();
        }

        let opcode = u16::from(group.opcode);
        emit_comment_version_blocks(
            &mut output,
            &emitted_versions,
            &extra,
            |v| (class_guid_str.clone(), opcode, v),
            releases,
        );

        writeln!(output, "//").unwrap();
    }

    writeln!(
        output,
        "// END Generated by etw-rs generate-provider (comment-only, MOF)."
    )
    .unwrap();

    output
}

/// Finds versions present in the release map but not reported by TDH.
///
/// Returns a sorted list of `(version, release_string)` pairs for the given
/// `class_key` and `event_id` that are absent from `known_versions`.
fn release_only_versions(
    releases: Option<&ReleaseMap>,
    class_key: &str,
    event_id: u16,
    known_versions: &HashSet<u8>,
) -> Vec<(u8, String)> {
    let Some(map) = releases else {
        return Vec::new();
    };
    let mut extra: Vec<(u8, String)> = map
        .iter()
        .filter(|((ck, eid, ver), _)| {
            ck == class_key && *eid == event_id && !known_versions.contains(ver)
        })
        .map(|((_, _, ver), rel)| (*ver, rel.clone()))
        .collect();
    extra.sort_by_key(|(v, _)| *v);
    extra.dedup_by_key(|(v, _)| *v);
    extra
}

/// Emits a comment line for a version only known from the release dataset.
#[expect(clippy::unwrap_used, reason = "write! to String is infallible")]
fn emit_release_only_version(output: &mut String, ver: u8, release: &str) {
    writeln!(output, "//").unwrap();
    writeln!(
        output,
        "// Version {ver}: not present on this OS // Since {release}"
    )
    .unwrap();
}

/// Field data for comment-only output.
struct CommentField {
    index: usize,
    name: String,
    in_type_name: String,
}

/// Version data for comment-only output.
struct CommentVersionOutput {
    version: u8,
    extends: Option<u8>,
    fields: Vec<CommentField>,
}

/// Emits comment-only version blocks, collapsing versions that share field names.
///
/// Three display modes:
/// 1. **Identical** — consecutive versions with the exact same fields are merged into a single `//
///    Versions X, Y:` header.
/// 2. **Name-extends** — a version whose field *names* are a prefix of the next version's names
///    (types may differ) is shown as `(extends vN):` with only changed types and new fields listed.
/// 3. **Divergent** — versions with structural differences get full field listings.
///
/// Release-only versions (known from the dataset but not present on this OS) are
/// interleaved in version order.
#[expect(clippy::unwrap_used, reason = "write! to String is infallible")]
fn emit_comment_version_blocks(
    output: &mut String,
    emitted_versions: &[CommentVersionOutput],
    extra: &[(u8, String)],
    release_key: impl Fn(u8) -> (String, u16, u8),
    releases: Option<&ReleaseMap>,
) {
    let mut extra_iter = extra.iter().peekable();

    // Resolve each version's display mode relative to the previous version.
    // `name_extends_from` is set when all field names of the previous version
    // appear as a prefix of this version's fields (types may differ).
    struct VersionDisplay {
        /// Indices into `emitted_versions` that share identical fields.
        versions: Vec<usize>,
        /// If set, this group name-extends a previous version (by index).
        name_extends_from: Option<usize>,
    }

    let mut groups: Vec<VersionDisplay> = Vec::new();

    for (i, ver) in emitted_versions.iter().enumerate() {
        if let Some(last_group) = groups.last() {
            let prev = &emitted_versions[*last_group.versions.last().unwrap()];

            // Check for identical fields (same names AND types, same count).
            let is_identical = prev.fields.len() == ver.fields.len()
                && prev
                    .fields
                    .iter()
                    .zip(&ver.fields)
                    .all(|(p, c)| p.name == c.name && p.in_type_name == c.in_type_name);

            if is_identical {
                // Merge into the current group.
                #[expect(clippy::unwrap_used, reason = "just checked is_some via last()")]
                groups.last_mut().unwrap().versions.push(i);
                continue;
            }

            // Check for name-prefix extension: all field NAMES of the base version's
            // representative appear as a prefix of this version's field names.
            let base_idx = last_group.versions[0];
            let base = &emitted_versions[base_idx];
            let names_match = base.fields.len() <= ver.fields.len()
                && base
                    .fields
                    .iter()
                    .zip(&ver.fields)
                    .all(|(p, c)| p.name == c.name);

            if names_match {
                groups.push(VersionDisplay {
                    versions: vec![i],
                    name_extends_from: Some(base_idx),
                });
                continue;
            }
        }

        // No relation to the previous group — start a new standalone group.
        groups.push(VersionDisplay {
            versions: vec![i],
            name_extends_from: None,
        });
    }

    // Emit each group.
    for group in &groups {
        let base_idx = group.versions[0];
        let base = &emitted_versions[base_idx];
        let version_nums: Vec<u8> = group
            .versions
            .iter()
            .map(|&i| emitted_versions[i].version)
            .collect();

        // Emit any release-only versions that sort before this group.
        while extra_iter.peek().is_some_and(|(v, _)| *v < version_nums[0]) {
            let (v, rel) = extra_iter.next().unwrap();
            emit_release_only_version(output, *v, rel);
        }

        // Build the release suffix.
        let release_suffix = build_release_suffix(&version_nums, &release_key, releases);

        // Build and emit the header line.
        writeln!(output, "//").unwrap();
        let extends_label = group.name_extends_from.map_or_else(
            || {
                if version_nums.len() == 1 {
                    base.extends
                        .map(|v| format!(" (extends v{v})"))
                        .unwrap_or_default()
                } else {
                    String::new()
                }
            },
            |prev_idx| format!(" (extends v{})", emitted_versions[prev_idx].version),
        );

        if version_nums.len() == 1 {
            writeln!(
                output,
                "// Version {}{extends_label}:{release_suffix}",
                version_nums[0]
            )
            .unwrap();
        } else {
            let ver_list: Vec<String> = version_nums.iter().map(ToString::to_string).collect();
            writeln!(
                output,
                "// Versions {}{extends_label}:{release_suffix}",
                ver_list.join(", ")
            )
            .unwrap();
        }

        // Determine which fields to show.
        if let Some(prev_idx) = group.name_extends_from {
            // Name-extends: show only type changes and new fields.
            let prev = &emitted_versions[prev_idx];
            emit_diff_fields(output, prev, base);
        } else if version_nums.len() > 1 {
            // Collapsed identical group — show all fields.
            emit_full_fields(output, &base.fields, 0);
        } else if let Some(ext_ver) = base.extends {
            // Strict prefix extension — show only new fields.
            let prefix_len = emitted_versions
                .iter()
                .find(|v| v.version == ext_ver)
                .map_or(0, |v| v.fields.len());
            emit_full_fields(output, &base.fields, prefix_len);
        } else {
            // Standalone — show all fields.
            emit_full_fields(output, &base.fields, 0);
        }
    }

    // Emit any remaining release-only versions.
    for (v, rel) in extra_iter {
        emit_release_only_version(output, *v, rel);
    }
}

/// Builds the trailing release comment for a group of version numbers.
fn build_release_suffix(
    version_nums: &[u8],
    release_key: &impl Fn(u8) -> (String, u16, u8),
    releases: Option<&ReleaseMap>,
) -> String {
    let annotations: Vec<String> = version_nums
        .iter()
        .filter_map(|&v| {
            let ann = release_annotation(releases, &release_key(v));
            if ann.is_empty() { None } else { Some(ann) }
        })
        .collect();

    if annotations.is_empty() {
        return String::new();
    }
    if annotations.len() == 1 || annotations.iter().all(|c| c == &annotations[0]) {
        return annotations[0].clone();
    }
    // Different annotations — list per-version.
    let parts: Vec<String> = version_nums
        .iter()
        .zip(annotations.iter())
        .map(|(v, ann)| format!("v{v}{ann}"))
        .collect();
    format!(" // {}", parts.join("; "))
}

/// Emits a full field listing starting from `start_index`.
#[expect(clippy::unwrap_used, reason = "write! to String is infallible")]
fn emit_full_fields(output: &mut String, fields: &[CommentField], start_index: usize) {
    let max_name = fields[start_index..]
        .iter()
        .map(|f| f.name.len())
        .max()
        .unwrap_or(0);

    for field in &fields[start_index..] {
        writeln!(
            output,
            "//   [{:>2}] {:<width$}  {}",
            field.index,
            field.name,
            field.in_type_name,
            width = max_name
        )
        .unwrap();
    }
}

/// Emits only the differences between `prev` and `curr` versions.
///
/// Shows fields whose type changed (with `(was TYPE)` annotation) and any
/// fields added beyond the previous version's field count.
#[expect(clippy::unwrap_used, reason = "write! to String is infallible")]
fn emit_diff_fields(output: &mut String, prev: &CommentVersionOutput, curr: &CommentVersionOutput) {
    // Collect fields to display: type changes + new fields.
    struct DiffEntry<'a> {
        field: &'a CommentField,
        annotation: Option<String>,
    }

    let mut entries: Vec<DiffEntry<'_>> = Vec::new();

    // Type changes within the overlapping range.
    for (p, c) in prev.fields.iter().zip(&curr.fields) {
        if p.in_type_name != c.in_type_name {
            entries.push(DiffEntry {
                field: c,
                annotation: Some(format!("was {}", p.in_type_name)),
            });
        }
    }

    // New fields beyond the previous version's count.
    for field in curr.fields.iter().skip(prev.fields.len()) {
        entries.push(DiffEntry {
            field,
            annotation: None,
        });
    }

    if entries.is_empty() {
        return;
    }

    let max_name = entries
        .iter()
        .map(|e| e.field.name.len())
        .max()
        .unwrap_or(0);
    let max_type = entries
        .iter()
        .map(|e| e.field.in_type_name.len())
        .max()
        .unwrap_or(0);

    for entry in &entries {
        let ann = entry
            .annotation
            .as_ref()
            .map(|a| format!("  ({a})"))
            .unwrap_or_default();
        writeln!(
            output,
            "//   [{:>2}] {:<name_w$}  {:<type_w$}{}",
            entry.field.index,
            entry.field.name,
            entry.field.in_type_name,
            ann,
            name_w = max_name,
            type_w = if ann.is_empty() { 0 } else { max_type },
        )
        .unwrap();
    }
}

//! Mixed-bitness parsing, through both the dynamic (TDH) and generated static paths.
//!
//! A user-mode provider emits events in the bitness of the *emitting* process,
//! so one provider/event/version can arrive with 4-byte or 8-byte `Pointer`
//! fields. The schema cache keys on provider/event/version/opcode **without**
//! bitness and stores a per-pointer-size parser cache alongside each schema,
//! because a TDH schema is bitness-independent while precomputed property
//! offsets are not.
//!
//! The failure mode that design must prevent is one bitness's offsets being
//! reused for the other. It can only appear when both bitnesses reach the same
//! cache, which no other test arranges: `32bit_events.rs` only ever asserts on
//! 32-bit events.
//!
//! # The static parser rides along
//!
//! Every event captured here is also parsed by the generated static parser and
//! required to agree with the dynamic one, field for field. The two derive their
//! offsets independently -- compile-time `OFFSET_32`/`OFFSET_64` constants chosen
//! by the header's bitness flag on one side, the TDH schema on the other -- so
//! agreement on a genuine 32-bit record is evidence about the generated
//! constants.
//!
//! `static_schema_pointer_size.rs` covers the same mechanism but cannot cover
//! this: there, one `event_schema!` declaration produces both the offsets under
//! test and the expectations they are checked against, so a generator that was
//! wrong about a real manifest would still pass. It is the shared-oracle flaw
//! that `common/differential.rs` exists to avoid, one level up.
//!
//! An offline fixture cannot substitute. TDH ignores
//! `EVENT_HEADER_FLAG_32_BIT_HEADER` on a synthesised record even for a
//! registered provider -- measured: it reads 8-byte pointers regardless, then
//! runs off the end of a 4-byte-pointer payload. So TDH is only a usable oracle
//! for 32-bit layouts when the record genuinely came from a 32-bit process.
//!
//! Poisoning is order-dependent — whichever bitness populates the cache first
//! is the one that could corrupt the second — so the pair of tests below
//! covers both directions. Process start-up order can't pick a direction
//! reliably (both PowerShells JIT before their sleep), so a priming gate in
//! the callback does instead, and `check()` asserts the resulting order
//! exactly, plus that both children are represented.
//!
//! `Microsoft-Windows-DotNETRuntime` event 20 (`GCSampledObjectAllocationHigh`)
//! is the vehicle: `Address` and `TypeID` are `Pointer`, and the fixed-width
//! fields after them only read back sanely if the pointer width was resolved
//! correctly.
//!
//! Nothing is asserted inside the event callback. A panic there tears down the
//! trace and resurfaces as an unrelated failure later in the test, which
//! destroys the diagnostic.
//!
//! Requirements: Administrator (or Performance Log Users) for ETW session
//! creation, and both 32-bit and 64-bit PowerShell present.


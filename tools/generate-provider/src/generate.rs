/// Sanitises an event name into a valid Rust identifier for parser struct naming.
///
/// Removes spaces and non-alphanumeric characters while preserving PascalCase.
/// E.g., "LoggingWrite Buffer" -> "LoggingWriteBuffer", "Lost Event" -> "LostEvent".
fn sanitise_parser_name(name: &str) -> String {
    let mut result = String::with_capacity(name.len());
    let mut capitalize_next = false;
    for (i, ch) in name.chars().enumerate() {
        if ch == ' ' || (!ch.is_alphanumeric() && ch != '_') {
            capitalize_next = true;
        } else if capitalize_next {
            result.push(ch.to_ascii_uppercase());
            capitalize_next = false;
        } else {
            result.push(ch);
        }
        // Ensure first char is uppercase
        if i == 0 && result.len() == 1 {
            #[expect(clippy::unwrap_used, reason = "just pushed a char")]
            let c = result.pop().unwrap();
            result.push(c.to_ascii_uppercase());
        }
    }
    if result.is_empty() {
        return "Unknown".to_owned();
    }
    // Ensure it doesn't start with a digit
    if result.starts_with(|c: char| c.is_ascii_digit()) {
        result.insert(0, '_');
    }
    result
}

/// Sanitises a field name to be a valid Rust identifier.
fn sanitise_field_name(name: &str) -> String {
    let mut result = String::with_capacity(name.len());
    for (i, ch) in name.chars().enumerate() {
        if ch.is_alphanumeric() || ch == '_' {
            result.push(ch);
        } else if i > 0 {
            result.push('_');
        }
    }

    // Ensure it doesn't start with a digit
    if result.starts_with(|c: char| c.is_ascii_digit()) {
        result.insert(0, '_');
    }

    // Avoid Rust keywords
    if matches!(
        result.as_str(),
        "as" | "async"
            | "await"
            | "break"
            | "const"
            | "continue"
            | "crate"
            | "dyn"
            | "else"
            | "enum"
            | "extern"
            | "false"
            | "fn"
            | "for"
            | "if"
            | "impl"
            | "in"
            | "let"
            | "loop"
            | "match"
            | "mod"
            | "move"
            | "mut"
            | "pub"
            | "ref"
            | "return"
            | "self"
            | "static"
            | "struct"
            | "super"
            | "trait"
            | "true"
            | "type"
            | "unsafe"
            | "use"
            | "where"
            | "while"
            | "yield"
    ) {
        result.push('_');
    }

    result
}

/// Returns the names of keywords whose bits are set in the event's keyword mask.
fn matching_keyword_names(event_keyword: u64, keywords: &[ProviderFieldInfo]) -> Vec<String> {
    if event_keyword == 0 {
        return Vec::new();
    }
    keywords
        .iter()
        .filter(|kw| kw.value != 0 && event_keyword & kw.value == kw.value)
        .map(|kw| kw.name.clone())
        .collect()
}


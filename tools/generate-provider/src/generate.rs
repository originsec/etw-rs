/// Generates a complete provider file for a MOF provider.
///
/// MOF providers identify events by `(class_guid, opcode, version)` instead of
/// `(provider_guid, event_id, version)`. The generated file uses `pub mod opcode`
/// instead of `pub mod event`, and the `provider_schema!` block uses the opcode
/// as the `id:` field.
///
/// Events are grouped by class GUID when the provider has multiple class GUIDs.
#[expect(clippy::unwrap_used, reason = "write! to String is infallible")]
pub fn generate_mof_file(
    provider: &MofProvider,
    display_name: Option<&str>,
    keywords: &[ProviderFieldInfo],
    releases: Option<&ReleaseMap>,
    extra_flags: &str,
    drop_old: bool,
) -> String {
    let name = display_name.unwrap_or(&provider.name);
    let guid_u128 = guid_to_u128(&provider.provider_guid);
    let guid_literal = format_guid_u128(guid_u128);

    let mut content = String::new();
    // Backtick single-word names to satisfy clippy::doc_markdown (e.g. FileIo → `FileIo`).
    let doc_name = if name.contains(' ') {
        name.to_owned()
    } else {
        format!("`{name}`")
    };
    writeln!(content, "//! {doc_name} provider (MOF/classic)").unwrap();
    content.push('\n');
    writeln!(content, "// Generated by etw-rs generate-provider.").unwrap();
    write_regenerate_comment(
        &mut content,
        &format!("generate-provider \"{name}\"{extra_flags}"),
    );
    writeln!(
        content,
        "#![allow(unused, reason = \"generated provider schema — constants consumed on demand\")]"
    )
    .unwrap();
    if name != provider.name {
        writeln!(content, "// WMI class: {}", provider.name).unwrap();
    }
    writeln!(
        content,
        "// Note: MOF events use (class_guid, opcode, version) identification."
    )
    .unwrap();
    content.push('\n');

    writeln!(content, "use etw::Guid;").unwrap();
    content.push('\n');
    writeln!(content, "pub const NAME: &str = \"{name}\";").unwrap();
    writeln!(
        content,
        "pub const GUID: Guid = Guid::from_u128(0x{guid_literal});"
    )
    .unwrap();

    // Skip enable_flags when per-class PERF_* masks are available
    let has_perf_masks = provider
        .events
        .iter()
        .any(|ev| !guid_to_perf_masks(&etw::Guid::from_u128(ev.class_guid.to_u128())).is_empty());

    if !has_perf_masks {
        let ef_entries: Vec<_> = keywords
            .iter()
            .map(|kw| {
                let n = keyword_name_to_rust(&kw.name);
                let v = format_hex_grouped(kw.value);
                (n, v)
            })
            .collect();
        emit_const_module(
            &mut content,
            "enable_flags",
            "u32",
            &ef_entries
                .iter()
                .map(|(n, v)| (n.as_str(), v.clone()))
                .collect::<Vec<_>>(),
            Some("Enable flags for classic event control."),
            None,
        );
    }

    // Deduplicate events by (class_guid, opcode, version)
    let mut seen = HashSet::new();
    let mut unique_events = Vec::new();
    for ev in &provider.events {
        let key = (guid_to_u128(&ev.class_guid), ev.opcode, ev.version);
        if seen.insert(key) {
            unique_events.push(ev);
        }
    }

    // Group events by class GUID
    let mut by_class: HashMap<u128, Vec<_>> = HashMap::new();
    for ev in &unique_events {
        let key = guid_to_u128(&ev.class_guid);
        by_class.entry(key).or_default().push(*ev);
    }
    let multi_class = by_class.len() > 1;

    // Generate opcode constants — only for opcodes with meaningful WMI names.
    // Generic fallbacks like `OPCODE_0 = 0` add no value and are omitted.
    let mut opcode_names: Vec<(u8, String)> = Vec::new();
    let mut used_opcode_names: HashSet<String> = HashSet::new();
    let mut used_opcode_values: HashSet<u8> = HashSet::new();
    for ev in &unique_events {
        if !used_opcode_values.insert(ev.opcode) {
            continue;
        }
        if ev.event_type_name.is_empty() {
            continue;
        }
        let rust_name = event_name_to_rust(&ev.event_type_name);
        if rust_name.is_empty() || !used_opcode_names.insert(rust_name.clone()) {
            continue;
        }
        opcode_names.push((ev.opcode, rust_name));
    }
    opcode_names.sort_by_key(|(op, _)| *op);

    let op_entries: Vec<_> = opcode_names
        .iter()
        .map(|(op, name)| (name.as_str(), op.to_string()))
        .collect();
    emit_const_module(
        &mut content,
        "opcode",
        "u8",
        &op_entries,
        Some("Opcode constants for MOF event identification."),
        None,
    );

    // Build class GUID → constant name mapping. Used both by the class_guid module
    // and the schema block (to emit `class_guid: class_guid::CONST,` per event).
    let mut class_guid_names: HashMap<u128, String> = HashMap::new();
    {
        let mut used_class_names: HashSet<String> = HashSet::new();
        let mut sorted_classes: Vec<_> = by_class.iter().collect();
        sorted_classes.sort_by(|a, b| {
            let name_a =
                a.1.first()
                    .map(|e| strip_version_suffix(&e.class_name).to_lowercase());
            let name_b =
                b.1.first()
                    .map(|e| strip_version_suffix(&e.class_name).to_lowercase());
            name_a.cmp(&name_b)
        });
        for (key, events) in &sorted_classes {
            let first = events[0];
            let const_name = if first.class_name.is_empty() {
                format!("CLASS_{key:032X}")
            } else {
                let stripped = strip_version_suffix(&first.class_name);
                let rust_name = event_name_to_rust(stripped);
                if used_class_names.contains(&rust_name) {
                    event_name_to_rust(&first.class_name)
                } else {
                    used_class_names.insert(rust_name.clone());
                    rust_name
                }
            };
            class_guid_names.insert(**key, const_name);
        }

        // Emit class GUIDs module if there are multiple classes
        if multi_class {
            let cg_entries: Vec<_> = sorted_classes
                .iter()
                .map(|(key, _)| {
                    let const_name = &class_guid_names[key];
                    let lit = format_guid_u128(**key);
                    (const_name.as_str(), format!("Guid::from_u128(0x{lit})"))
                })
                .collect();
            emit_const_module(
                &mut content,
                "class_guid",
                "GUID",
                &cg_entries,
                Some("Event class GUIDs used as `ProviderId` in classic events."),
                Some("use etw::Guid;"),
            );
        }
    }

    // Generate schema block
    content.push('\n');
    let schema = generate_mof_schema_block(
        &unique_events,
        name,
        &provider.provider_guid,
        multi_class,
        &class_guid_names,
        extra_flags,
        releases,
        drop_old,
    );
    content.push_str(&schema);

    content
}

/// Generates only the provider metadata for a MOF provider (NAME, GUID, enable_flags,
/// opcodes, class_guids) without the `provider_schema!` block.
#[expect(clippy::unwrap_used, reason = "write! to String is infallible")]
pub fn generate_mof_provider_only(
    provider: &MofProvider,
    display_name: Option<&str>,
    keywords: &[ProviderFieldInfo],
) -> String {
    let name = display_name.unwrap_or(&provider.name);
    let guid_u128 = guid_to_u128(&provider.provider_guid);
    let guid_literal = format_guid_u128(guid_u128);

    let mut content = String::new();
    // Backtick single-word names to satisfy clippy::doc_markdown (e.g. FileIo → `FileIo`).
    let doc_name = if name.contains(' ') {
        name.to_owned()
    } else {
        format!("`{name}`")
    };
    writeln!(content, "//! {doc_name} provider (MOF/classic)").unwrap();
    content.push('\n');
    writeln!(content, "// Generated by etw-rs generate-provider.").unwrap();
    write_regenerate_comment(
        &mut content,
        &format!("generate-provider \"{name}\" --mof --provider-only"),
    );
    writeln!(
        content,
        "#![allow(unused, reason = \"generated provider schema — constants consumed on demand\")]"
    )
    .unwrap();
    if name != provider.name {
        writeln!(content, "// WMI class: {}", provider.name).unwrap();
    }
    writeln!(
        content,
        "// Note: MOF events use (class_guid, opcode, version) identification."
    )
    .unwrap();
    content.push('\n');

    writeln!(content, "use etw::Guid;").unwrap();
    content.push('\n');
    writeln!(content, "pub const NAME: &str = \"{name}\";").unwrap();
    writeln!(
        content,
        "pub const GUID: Guid = Guid::from_u128(0x{guid_literal});"
    )
    .unwrap();

    // Only emit enable_flags for multi-class outputs (e.g. "Windows Kernel Trace").
    // Single-class outputs represent an individual event class, not the full provider.
    let class_guids: HashSet<_> = provider.events.iter().map(|ev| ev.class_guid).collect();

    if class_guids.len() > 1 {
        let ef_entries: Vec<_> = keywords
            .iter()
            .map(|kw| {
                let n = keyword_name_to_rust(&kw.name);
                let v = format_hex_grouped(kw.value);
                (n, v)
            })
            .collect();
        emit_const_module(
            &mut content,
            "enable_flags",
            "u32",
            &ef_entries
                .iter()
                .map(|(n, v)| (n.as_str(), v.clone()))
                .collect::<Vec<_>>(),
            Some("Enable flags for classic event control."),
            None,
        );
    }

    // Deduplicate events by (class_guid, opcode, version)
    let mut seen = HashSet::new();
    let mut unique_events = Vec::new();
    for ev in &provider.events {
        let key = (guid_to_u128(&ev.class_guid), ev.opcode, ev.version);
        if seen.insert(key) {
            unique_events.push(ev);
        }
    }

    // Group events by class GUID
    let mut by_class: HashMap<u128, Vec<_>> = HashMap::new();
    for ev in &unique_events {
        let key = guid_to_u128(&ev.class_guid);
        by_class.entry(key).or_default().push(*ev);
    }

    // Sort classes alphabetically by name for stable output
    let mut used_class_names: HashSet<String> = HashSet::new();
    let mut sorted_classes: Vec<_> = by_class.iter().collect();
    sorted_classes.sort_by(|a, b| {
        let name_a =
            a.1.first()
                .map(|e| strip_version_suffix(&e.class_name).to_lowercase());
        let name_b =
            b.1.first()
                .map(|e| strip_version_suffix(&e.class_name).to_lowercase());
        name_a.cmp(&name_b)
    });

    // Build per-class info: (const_name, mod_name, guid_literal, opcodes)
    let class_info: Vec<_> = sorted_classes
        .iter()
        .map(|(key, events)| {
            let first = events[0];
            let const_name = if first.class_name.is_empty() {
                format!("CLASS_{key:032X}")
            } else {
                let stripped = strip_version_suffix(&first.class_name);
                let rust_name = event_name_to_rust(stripped);
                if used_class_names.contains(&rust_name) {
                    event_name_to_rust(&first.class_name)
                } else {
                    used_class_names.insert(rust_name.clone());
                    rust_name
                }
            };
            let mod_name = const_name.to_lowercase();
            let guid_lit = format_guid_u128(**key);

            // Collect unique opcodes for this class.
            // Use EventTypeName from WMI when available, then fall back to
            // TDH opcode names via get_mof_event_name().
            let class_guid = events[0].class_guid;
            let class_name = &events[0].class_name;
            let prefix = format!("{const_name}_");

            // Phase 1: resolve each unique opcode to a base name
            let mut candidates: Vec<(u8, String)> = Vec::new();
            let mut seen_opcodes: HashSet<u8> = HashSet::new();
            for ev in *events {
                if !seen_opcodes.insert(ev.opcode) {
                    continue;
                }
                let raw_name = if !ev.event_type_name.is_empty() {
                    ev.event_type_name.clone()
                } else if let Some(tdh) = get_mof_event_name(&class_guid, ev.opcode, ev.version) {
                    tdh
                } else if !ev.wmi_class_name.is_empty() {
                    // Grandchild event classes (e.g. SampledProfile under PerfInfo)
                    // may lack EventTypeName but have a WMI class name we can use.
                    strip_version_suffix(&ev.wmi_class_name).to_owned()
                } else {
                    continue;
                };
                // Normalise doubled/cased prefixes (e.g., "ALPCAlpc_Send" → "Alpc_Send")
                let normalised = normalize_mof_event_name(&raw_name, class_name);
                let rust_name = event_name_to_rust(&normalised);
                let rust_name = rust_name
                    .strip_prefix(&prefix)
                    .unwrap_or(&rust_name)
                    .to_owned();
                if !rust_name.is_empty() {
                    candidates.push((ev.opcode, rust_name));
                }
            }

            // Phase 2: sort by opcode so lower values claim clean names first
            candidates.sort_by_key(|(op, _)| *op);

            // Phase 3: assign final names, appending opcode on collision
            let mut opcodes: Vec<(u8, String)> = Vec::new();
            let mut used_names: HashSet<String> = HashSet::new();
            for (op, name) in candidates {
                let final_name = if used_names.contains(&name) {
                    format!("{name}_{op}")
                } else {
                    name
                };
                used_names.insert(final_name.clone());
                opcodes.push((op, final_name));
            }

            let group_id = guid_to_group_id(&etw::Guid::from_u128(class_guid.to_u128()));
            let perf_masks = guid_to_perf_masks(&etw::Guid::from_u128(class_guid.to_u128()));
            (
                const_name, mod_name, guid_lit, opcodes, group_id, perf_masks,
            )
        })
        .collect();

    // Per-class modules with GUID, PERF_* masks, opcode submodule, and optional hook_id
    // submodule. Single-class output is flattened to avoid double nesting
    // (e.g. thread::thread::GUID). Multi-class modules get #[rustfmt::skip] to preserve
    // column-aligned constants; flattened PERF_* constants accept rustfmt normalisation.
    let flatten = class_info.len() == 1;
    let (i1, i2) = if flatten {
        ("", "    ")
    } else {
        ("    ", "        ")
    };

    for (_, mod_name, guid_lit, opcodes, group_id, perf_masks) in &class_info {
        content.push('\n');
        if flatten {
            writeln!(
                content,
                "pub const CLASS_GUID: Guid = Guid::from_u128(0x{guid_lit});"
            )
            .unwrap();
        } else {
            writeln!(content, "#[rustfmt::skip]").unwrap();
            writeln!(content, "pub mod {mod_name} {{").unwrap();
            writeln!(content, "{i1}use etw::Guid;").unwrap();
            writeln!(
                content,
                "{i1}pub const GUID: Guid = Guid::from_u128(0x{guid_lit});"
            )
            .unwrap();
        }

        // PERF_* group mask constants for enabling this event class.
        // Multi-class modules are #[rustfmt::skip] so alignment is preserved;
        // flattened output uses plain formatting.
        if !perf_masks.is_empty() {
            if flatten {
                for (name, value) in *perf_masks {
                    writeln!(content, "pub const {name}: u32 = 0x{value:08X};").unwrap();
                }
            } else {
                let max_name = perf_masks.iter().map(|(n, _)| n.len()).max().unwrap_or(0);
                for (name, value) in *perf_masks {
                    writeln!(
                        content,
                        "{i1}pub const {:<name_w$} u32 = 0x{value:08X};",
                        format!("{name}:"),
                        name_w = max_name + 1,
                    )
                    .unwrap();
                }
            }
        }

        if !opcodes.is_empty() {
            content.push('\n');
            writeln!(content, "{i1}/// Event opcodes.").unwrap();
            if flatten {
                writeln!(content, "{i1}#[rustfmt::skip]").unwrap();
            }
            writeln!(content, "{i1}pub mod opcode {{").unwrap();

            let max_name = opcodes.iter().map(|(_, n)| n.len()).max().unwrap_or(0);
            let max_val = opcodes
                .iter()
                .map(|(op, _)| format!("{op}").len())
                .max()
                .unwrap_or(0);
            for (op, name) in opcodes {
                writeln!(
                    content,
                    "{i2}pub const {:<name_w$} u8 = {:>val_w$}",
                    format!("{name}:"),
                    format!("{op};"),
                    name_w = max_name + 1,
                    val_w = max_val + 1,
                )
                .unwrap();
            }
            writeln!(content, "{i1}}}").unwrap();
        }

        // hook_id submodule: (group_id << 8) | opcode for stack walk configuration
        if let Some(gid) = group_id
            && !opcodes.is_empty()
        {
            content.push('\n');
            writeln!(
                content,
                "{i1}/// Hook IDs for stack walking and LBR tracing."
            )
            .unwrap();
            if flatten {
                writeln!(content, "{i1}#[rustfmt::skip]").unwrap();
            }
            writeln!(content, "{i1}pub mod hook_id {{").unwrap();

            let max_name = opcodes.iter().map(|(_, n)| n.len()).max().unwrap_or(0);
            for (op, name) in opcodes {
                let hook = (u16::from(*gid) << 8) | u16::from(*op);
                writeln!(
                    content,
                    "{i2}pub const {:<name_w$} u16 = 0x{hook:04X};",
                    format!("{name}:"),
                    name_w = max_name + 1,
                )
                .unwrap();
            }
            writeln!(content, "{i1}}}").unwrap();
        }

        if !flatten {
            writeln!(content, "}}").unwrap();
        }
    }

    content
}


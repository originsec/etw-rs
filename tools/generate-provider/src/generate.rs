/// Generates a complete provider file from TDH metadata.
///
/// Returns a Rust source file containing:
/// - `NAME` and `GUID` constants
/// - `keyword` module with keyword constants
/// - `event` module with event ID constants
/// - `provider_schema!` block with static field schemas
#[expect(clippy::unwrap_used, reason = "write! to String is infallible")]
pub fn generate_full_file(
    provider_name: &str,
    guid: &GUID,
    events: &[ProviderEventInfo],
    keywords: &[ProviderFieldInfo],
    releases: Option<&ReleaseMap>,
    extra_flags: &str,
    drop_old: bool,
) -> String {
    let guid_u128 = guid_to_u128(guid);
    let guid_literal = format_guid_u128(guid_u128);

    // Deduplicate events by ID (keep first version seen)
    let mut seen_ids = HashSet::new();
    let mut unique_events: Vec<&ProviderEventInfo> = Vec::new();
    for ev in events {
        if seen_ids.insert(ev.id) {
            unique_events.push(ev);
        }
    }
    unique_events.sort_by_key(|e| e.id);

    // Generate event names, ensuring no duplicates
    let event_names = generate_event_names(guid, &unique_events, keywords);

    // Build file content
    let mut content = String::new();
    writeln!(content, "//! {provider_name} provider").unwrap();
    content.push('\n');
    writeln!(content, "// Generated by etw-rs generate-provider.").unwrap();
    write_regenerate_comment(
        &mut content,
        &format!("generate-provider {provider_name}{extra_flags}"),
    );
    writeln!(
        content,
        "#![allow(unused, reason = \"generated provider schema — constants consumed on demand\")]"
    )
    .unwrap();
    content.push('\n');

    writeln!(content, "use etw::Guid;").unwrap();
    content.push('\n');
    writeln!(content, "pub const NAME: &str = \"{provider_name}\";").unwrap();
    writeln!(
        content,
        "pub const GUID: Guid = Guid::from_u128(0x{guid_literal});"
    )
    .unwrap();

    // Keywords module
    let kw_entries: Vec<_> = keywords
        .iter()
        .map(|kw| {
            let n = keyword_name_to_rust(&kw.name);
            let v = format_hex_grouped(kw.value);
            (n, v)
        })
        .collect();
    emit_const_module(
        &mut content,
        "keyword",
        "u64",
        &kw_entries
            .iter()
            .map(|(n, v)| (n.as_str(), v.clone()))
            .collect::<Vec<_>>(),
        None,
        None,
    );

    // Events module
    let ev_entries: Vec<_> = event_names
        .iter()
        .map(|(id, name)| (name.as_str(), id.to_string()))
        .collect();
    emit_const_module(&mut content, "event", "u16", &ev_entries, None, None);

    // Schema block
    let schema = generate_schema_block(
        provider_name,
        guid,
        events,
        keywords,
        extra_flags,
        releases,
        drop_old,
    );
    content.push('\n');
    content.push_str(&schema);

    content
}


/// Generates unique Rust names for each event, handling duplicates via keyword fallback.
///
/// Two-pass approach: first compute base names from task/opcode, then detect
/// collisions and add keyword suffixes to *all* events that share a base name
/// (not just the second occurrence) for consistency.
fn generate_event_names(
    guid: &GUID,
    unique_events: &[&ProviderEventInfo],
    keywords: &[ProviderFieldInfo],
) -> Vec<(u16, String)> {
    // Pass 1: compute base Rust name and opcode-only alternative for each event.
    let name_info: Vec<(String, Option<String>)> = unique_events
        .iter()
        .map(|ev| {
            get_best_event_name(guid, ev, unique_events, keywords)
                .map(|(full, opcode_only)| {
                    (
                        event_name_to_rust(&full),
                        opcode_only.map(|o| event_name_to_rust(&o)),
                    )
                })
                .unwrap_or_default()
        })
        .collect();

    let base_names: Vec<&str> = name_info.iter().map(|(b, _)| b.as_str()).collect();

    // Count how many events share each non-empty base name.
    let mut name_counts: HashMap<&str, usize> = HashMap::new();
    for name in &base_names {
        if !name.is_empty() {
            *name_counts.entry(name).or_default() += 1;
        }
    }

    // Also count opcode-only names to check their uniqueness.
    let mut opcode_counts: HashMap<&str, usize> = HashMap::new();
    for (_, opcode_only) in &name_info {
        if let Some(o) = opcode_only.as_ref().filter(|s| !s.is_empty()) {
            *opcode_counts.entry(o.as_str()).or_default() += 1;
        }
    }

    // Pass 2: assign final names. For collisions, try opcode-only (if unique),
    // then keyword name, then _{id} fallback.
    let mut used_names: HashSet<String> = HashSet::new();
    let mut event_names: Vec<(u16, String)> = Vec::new();

    for (i, ev) in unique_events.iter().enumerate() {
        let base = base_names[i];
        let opcode_only = name_info[i].1.as_deref();
        let is_collision = !base.is_empty() && name_counts.get(base).copied().unwrap_or(0) > 1;

        let name = if base.is_empty() {
            // No manifest name at all
            let fallback = format!("EVENT_{}", ev.id);
            used_names.insert(fallback.clone());
            fallback
        } else if !is_collision && !used_names.contains(base) {
            // Unique base name and not yet taken
            used_names.insert(base.to_owned());
            base.to_owned()
        } else {
            // Colliding base name, or base name already taken.
            // Try opcode-only when it's globally unique across the provider.
            let opcode_candidate = opcode_only.filter(|o| {
                !o.is_empty()
                    && opcode_counts.get(o).copied().unwrap_or(0) == 1
                    && !used_names.contains(*o)
            });

            if let Some(opcode_name) = opcode_candidate {
                used_names.insert(opcode_name.to_owned());
                opcode_name.to_owned()
            } else if let Some(kw) = get_event_keyword_name(guid, ev.keyword)
                .map(|kw| keyword_name_to_rust(&kw))
                .filter(|s| !s.is_empty())
            {
                // Multi-word keywords (e.g. SUSPEND_THREAD, ALLOCVM_REMOTE) are
                // descriptive enough to stand alone. Single-word keywords (e.g.
                // IPV4, IPV6) are classifiers that need the base for context.
                let is_descriptive = kw.contains('_');

                if is_descriptive && !used_names.contains(&kw) {
                    used_names.insert(kw.clone());
                    kw
                } else {
                    let combined = format!("{base}_{kw}");
                    if used_names.contains(&combined) {
                        let id_name = format!("{base}_{}", ev.id);
                        used_names.insert(id_name.clone());
                        id_name
                    } else {
                        used_names.insert(combined.clone());
                        combined
                    }
                }
            } else {
                // No keyword available — fall back to _{id}
                let id_name = format!("{base}_{}", ev.id);
                used_names.insert(id_name.clone());
                id_name
            }
        };

        event_names.push((ev.id, name));
    }

    event_names
}


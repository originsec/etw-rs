/// Generates a comment-only summary of event fields for a manifest provider.
///
/// Produces the same information as `generate_schema_block` but rendered as
/// pure `//` comments with no compilable code. Useful for quick reference.
#[expect(clippy::unwrap_used, reason = "write! to String is infallible")]
pub fn generate_comment_block(
    provider_name: &str,
    guid: &GUID,
    events: &[ProviderEventInfo],
    keywords: &[ProviderFieldInfo],
    extra_flags: &str,
    releases: Option<&ReleaseMap>,
    drop_old: bool,
) -> String {
    // Deduplicate events by (id, version), then group by id
    let mut seen = HashSet::new();
    let mut unique_events = Vec::new();
    for ev in events {
        if seen.insert((ev.id, ev.version)) {
            unique_events.push(ev);
        }
    }
    unique_events.sort_by_key(|e| (e.id, e.version));

    // Group consecutive events by ID
    let mut groups: Vec<(u16, Vec<&ProviderEventInfo>)> = Vec::new();
    for ev in &unique_events {
        if groups.last().is_some_and(|(id, _)| *id == ev.id) {
            #[expect(clippy::unwrap_used, reason = "just checked is_some_and")]
            groups.last_mut().unwrap().1.push(ev);
        } else {
            groups.push((ev.id, vec![ev]));
        }
    }

    let mut output = String::new();

    writeln!(
        output,
        "// BEGIN Generated by etw-rs generate-provider (comment-only)."
    )
    .unwrap();
    write_regenerate_comment(
        &mut output,
        &format!("generate-provider {provider_name}{extra_flags}"),
    );
    writeln!(output, "//").unwrap();

    let all_events: Vec<&ProviderEventInfo> = events.iter().collect();
    for (id, versions) in &groups {
        let first_ev = versions[0];
        let event_name =
            get_best_event_name(guid, first_ev, &all_events, keywords).map(|(full, _)| full);
        let name_str = event_name.as_deref().unwrap_or("unknown");

        // Resolve keyword names
        let keyword_names = matching_keyword_names(first_ev.keyword, keywords);

        // Header
        writeln!(output, "// Event: {name_str} (id {id})").unwrap();
        if !keyword_names.is_empty() {
            writeln!(output, "// Keywords: {}", keyword_names.join(" | ")).unwrap();
        }

        // Collect version field data
        let mut emitted_versions: Vec<CommentVersionOutput> = Vec::new();
        let mut skipped: Vec<String> = Vec::new();

        for ev in versions {
            let fields = match get_event_fields(guid, ev) {
                Ok(f) => f,
                Err(e) => {
                    skipped.push(format!(
                        "// Skipped v{}: error querying fields: {e}",
                        ev.version
                    ));
                    continue;
                }
            };

            if fields.is_empty() {
                skipped.push(format!("// v{}: no fields", ev.version));
                continue;
            }

            let comment_fields: Vec<CommentField> = fields
                .iter()
                .enumerate()
                .map(|(i, f)| CommentField {
                    index: i,
                    name: sanitise_field_name(&f.name),
                    in_type_name: intype_name(f.in_type).to_owned(),
                })
                .collect();

            // Detect prefix extension
            let extends = emitted_versions.last().and_then(|prev| {
                (prev.fields.len() <= comment_fields.len()
                    && prev
                        .fields
                        .iter()
                        .zip(&comment_fields)
                        .all(|(p, c)| p.name == c.name && p.in_type_name == c.in_type_name))
                .then_some(prev.version)
            });

            emitted_versions.push(CommentVersionOutput {
                version: ev.version,
                extends,
                fields: comment_fields,
            });
        }

        // Drop old versions not in the release dataset, unless they have
        // identical fields to an adjacent kept version.
        if drop_old {
            filter_old_comment_versions(&mut emitted_versions, releases, "", *id);
        }

        // Collect TDH-known version numbers for release-only check
        let known_versions: HashSet<u8> = versions.iter().map(|ev| ev.version).collect();

        // Versions only known from the release dataset (not on this OS)
        let extra = release_only_versions(releases, "", *id, &known_versions);

        // Emit skipped versions
        for s in &skipped {
            writeln!(output, "{s}").unwrap();
        }

        let id = *id;
        emit_comment_version_blocks(
            &mut output,
            &emitted_versions,
            &extra,
            |v| (String::new(), id, v),
            releases,
        );

        writeln!(output, "//").unwrap();
    }

    writeln!(
        output,
        "// END Generated by etw-rs generate-provider (comment-only)."
    )
    .unwrap();

    output
}


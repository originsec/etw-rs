/// A resolved field with type metadata for prefix detection and annotation.
struct ResolvedField {
    name: String,
    rust_type: String,
    /// Zero-based index in the original TDH property array.
    index: usize,
    /// Human-readable TDH InType name (e.g. "UInt32", "UnicodeString").
    in_type_name: String,
}

/// Generates the `etw::provider_schema! { ... }` block.
///
/// `extra_flags` is appended to the "To regenerate" comment (e.g. `" --event-only 42"`).
#[expect(clippy::unwrap_used, reason = "write! to String is infallible")]
pub fn generate_schema_block(
    provider_name: &str,
    guid: &GUID,
    events: &[ProviderEventInfo],
    keywords: &[ProviderFieldInfo],
    extra_flags: &str,
    releases: Option<&ReleaseMap>,
    drop_old: bool,
) -> String {
    // Deduplicate events by (id, version), then group by id
    let mut seen = HashSet::new();
    let mut unique_events = Vec::new();
    for ev in events {
        if seen.insert((ev.id, ev.version)) {
            unique_events.push(ev);
        }
    }
    unique_events.sort_by_key(|e| (e.id, e.version));

    // Group consecutive events by ID
    let mut groups: Vec<(u16, Vec<&ProviderEventInfo>)> = Vec::new();
    for ev in &unique_events {
        if groups.last().is_some_and(|(id, _)| *id == ev.id) {
            #[expect(clippy::unwrap_used, reason = "just checked is_some_and")]
            groups.last_mut().unwrap().1.push(ev);
        } else {
            groups.push((ev.id, vec![ev]));
        }
    }

    let is_event_only = extra_flags.contains("--event-only");

    let mut output = String::new();

    if is_event_only {
        writeln!(
            output,
            "// BEGIN Auto-generated by etw-rs generate-provider."
        )
        .unwrap();
    } else {
        writeln!(output, "// Auto-generated by etw-rs generate-provider.").unwrap();
    }
    write_regenerate_comment(
        &mut output,
        &format!("generate-provider {provider_name}{extra_flags}"),
    );
    writeln!(output, "etw::provider_schema! {{").unwrap();
    if is_event_only {
        let guid_literal = format_guid_u128(guid_to_u128(guid));
        writeln!(output, "    guid: Guid::from_u128(0x{guid_literal}),").unwrap();
    } else {
        writeln!(output, "    guid: GUID,").unwrap();
    }
    writeln!(output, "    events: {{").unwrap();

    let mut first_event = true;
    let mut used_parser_names: HashSet<String> = HashSet::new();

    let all_events: Vec<&ProviderEventInfo> = events.iter().collect();
    for (id, versions) in &groups {
        let first_ev = versions[0];
        let event_name =
            get_best_event_name(guid, first_ev, &all_events, keywords).map(|(full, _)| full);
        let name_str = event_name.as_deref().unwrap_or("unknown");

        // Resolve all versions for this event
        let mut emitted_versions: Vec<VersionOutput> = Vec::new();
        let mut skipped: Vec<String> = Vec::new();

        for ev in versions {
            let fields = match get_event_fields(guid, ev) {
                Ok(f) => f,
                Err(e) => {
                    skipped.push(format!(
                        "// Skipped v{}: error querying fields: {e}",
                        ev.version
                    ));
                    continue;
                }
            };

            match resolve_fields(&fields) {
                FieldResolution::NoFields => {
                    skipped.push(format!(
                        "// {name_str} (id {id}, v{}): no fields",
                        ev.version
                    ));
                }
                FieldResolution::Resolved {
                    emittable,
                    commented,
                } => {
                    if emittable.is_empty() {
                        let field_list: String = commented.join(", ");
                        skipped.push(format!(
                            "// Skipped v{}: all fields unsupported — {field_list}",
                            ev.version
                        ));
                        continue;
                    }

                    // Check if previous emitted version is an exact prefix
                    let extends = emitted_versions.last().and_then(|prev| {
                        (prev.resolved.len() <= emittable.len()
                            && prev
                                .resolved
                                .iter()
                                .zip(&emittable)
                                .all(|(p, c)| p.name == c.name && p.rust_type == c.rust_type))
                        .then_some(prev.version)
                    });

                    emitted_versions.push(VersionOutput {
                        version: ev.version,
                        extends,
                        resolved: emittable,
                        commented,
                    });
                }
            }
        }

        // Drop old versions not present in the release dataset, unless
        // they have identical fields to an adjacent kept version.
        if drop_old {
            let kept: Vec<bool> = emitted_versions
                .iter()
                .map(|v| should_keep_version(releases, "", *id, v.version))
                .collect();
            let mut retain = kept.clone();
            for (i, is_kept) in kept.iter().enumerate() {
                if !is_kept {
                    // Keep if an adjacent version has identical fields.
                    let fields_match = |a: &[ResolvedField], b: &[ResolvedField]| {
                        a.len() == b.len()
                            && a.iter()
                                .zip(b)
                                .all(|(x, y)| x.name == y.name && x.rust_type == y.rust_type)
                    };
                    let adj_match = (i > 0
                        && kept[i - 1]
                        && fields_match(
                            &emitted_versions[i].resolved,
                            &emitted_versions[i - 1].resolved,
                        ))
                        || (i + 1 < kept.len()
                            && kept[i + 1]
                            && fields_match(
                                &emitted_versions[i].resolved,
                                &emitted_versions[i + 1].resolved,
                            ));
                    retain[i] = adj_match;
                }
            }
            let mut idx = 0;
            emitted_versions.retain(|_| {
                let keep = retain[idx];
                idx += 1;
                keep
            });

            // Clear stale `extends` references to dropped versions.
            let remaining: HashSet<u8> = emitted_versions.iter().map(|v| v.version).collect();
            for v in &mut emitted_versions {
                if v.extends.is_some_and(|base| !remaining.contains(&base)) {
                    v.extends = None;
                }
            }
        }

        // Skip entire event block if nothing is emittable
        if emitted_versions.is_empty() && skipped.is_empty() {
            continue;
        }

        if !first_event {
            writeln!(output).unwrap();
        }
        first_event = false;

        // Build inline comment for the event line
        let keyword_names = matching_keyword_names(first_ev.keyword, keywords);
        let mut comment_parts = Vec::new();
        if let Some(name) = &event_name {
            comment_parts.push(name.clone());
        }
        if !keyword_names.is_empty() {
            comment_parts.push(format!("[{}]", keyword_names.join(", ")));
        }
        let inline_comment = if comment_parts.is_empty() {
            String::new()
        } else {
            format!(" // {}", comment_parts.join(" "))
        };

        // Emit skip comments outside the event block if nothing is emittable
        if emitted_versions.is_empty() {
            for s in &skipped {
                writeln!(output, "        {s}").unwrap();
            }
            continue;
        }

        // Resolve the parser struct name for this event.
        let base_name = event_name
            .as_deref()
            .map_or_else(|| format!("Event{id}"), sanitise_parser_name);
        let parser_name = if used_parser_names.contains(&base_name) {
            format!("{base_name}{id}")
        } else {
            base_name
        };
        used_parser_names.insert(parser_name.clone());

        writeln!(output, "        event {{{inline_comment}").unwrap();
        writeln!(output, "            id: {id},").unwrap();
        writeln!(output, "            name: \"{parser_name}\",").unwrap();

        for s in &skipped {
            writeln!(output, "            {s}").unwrap();
        }

        for ver in &emitted_versions {
            let fields_to_emit;
            let mut header = format!("{}", ver.version);
            if let Some(base_ver) = ver.extends {
                let prefix_len = emitted_versions
                    .iter()
                    .find(|v| v.version == base_ver)
                    .map_or(0, |v| v.resolved.len());
                write!(header, ", extends_version: {base_ver}").unwrap();
                fields_to_emit = &ver.resolved[prefix_len..];
            } else {
                fields_to_emit = &ver.resolved[..];
            }

            if !ver.commented.is_empty() {
                write!(header, ", truncated: true").unwrap();
            }

            // Optionally annotate with the Windows release that introduced this version
            let release_comment = release_annotation(releases, &(String::new(), *id, ver.version));

            writeln!(
                output,
                "            version {{ {header}, fields: {{{release_comment}"
            )
            .unwrap();
            let max_width = fields_to_emit
                .iter()
                .map(|f| f.name.len() + 2 + f.rust_type.len() + 1) // "name: type,"
                .max()
                .unwrap_or(0);
            for field in fields_to_emit {
                let field_part = format!("{}: {},", field.name, field.rust_type);
                writeln!(
                    output,
                    "                {:<width$} // [{}] {}",
                    field_part,
                    field.index,
                    field.in_type_name,
                    width = max_width
                )
                .unwrap();
            }
            for comment in &ver.commented {
                writeln!(output, "                // {comment}").unwrap();
            }
            writeln!(output, "            }}}}").unwrap();
        }

        writeln!(output, "        }}").unwrap();
    }

    writeln!(output, "    }}").unwrap();
    writeln!(output, "}}").unwrap();
    if is_event_only {
        writeln!(output, "// END Auto-generated by etw-rs generate-provider.").unwrap();
    }

    output
}

/// The earliest release in the Windows10EtwEvents repo.
const EARLIEST_RELEASE: &str = "Windows 10 1511";

/// Builds the inline release annotation for a version line.
///
/// Returns an empty string when no release map was provided (i.e. `--query-release`
/// was not used). When a map is present:
/// - Earliest release → `" // Since Windows 10 1511 (or earlier)"`
/// - Known later release → `" // Since Windows 10 1903"`
/// - Missing from dataset → `" // Release not in dataset"`
fn release_annotation(releases: Option<&ReleaseMap>, key: &(String, u16, u8)) -> String {
    let Some(map) = releases else {
        return String::new();
    };
    match map.get(key) {
        Some(r) if r == EARLIEST_RELEASE => format!(" // Since {r} (or earlier)"),
        Some(r) => format!(" // Since {r}"),
        None => " // Release not in dataset".to_owned(),
    }
}

/// Returns `true` if a version should be kept given the release dataset.
///
/// A version is dropped when ANY of the following are true:
/// 1. It is absent from the dataset AND below the maximum tracked version (predates the dataset
///    entirely).
/// 2. It appeared in the earliest tracked release AND a strictly higher version also appeared in
///    that same release (already superseded before tracking began).
///
/// Versions above the maximum tracked version are assumed to be newer than the
/// dataset and are always kept.
fn should_keep_version(
    releases: Option<&ReleaseMap>,
    class_key: &str,
    event_id: u16,
    version: u8,
) -> bool {
    let Some(map) = releases else {
        return true;
    };

    let owned_key = (class_key.to_owned(), event_id, version);

    // Collect all versions for this event in the dataset.
    let event_versions: Vec<(u8, &str)> = map
        .iter()
        .filter(|((ck, eid, _), _)| ck == class_key && *eid == event_id)
        .map(|((_, _, v), rel)| (*v, rel.as_str()))
        .collect();

    // No tracked versions at all for this event — keep everything.
    if event_versions.is_empty() {
        return true;
    }

    let max_tracked = event_versions.iter().map(|(v, _)| *v).max().unwrap_or(0);

    // Version is above the dataset's maximum — likely newer, keep it.
    if version > max_tracked {
        return true;
    }

    // Version is absent from the dataset — drop it.
    let Some(release) = map.get(&owned_key) else {
        return false;
    };

    // Version is present, but check if it was already superseded in the
    // earliest tracked release. If a higher version shares the same earliest
    // release, this version was already old when tracking began.
    if release == EARLIEST_RELEASE {
        let higher_in_same_release = event_versions
            .iter()
            .any(|(v, rel)| *v > version && *rel == EARLIEST_RELEASE);
        if higher_in_same_release {
            return false;
        }
    }

    true
}

/// Removes old versions from the comment-only version list.
///
/// Keeps versions that are either in the release dataset, newer than the
/// dataset's maximum, or have identical fields to an adjacent kept version.
fn filter_old_comment_versions(
    versions: &mut Vec<CommentVersionOutput>,
    releases: Option<&ReleaseMap>,
    class_key: &str,
    event_id: u16,
) {
    let kept: Vec<bool> = versions
        .iter()
        .map(|v| should_keep_version(releases, class_key, event_id, v.version))
        .collect();

    let mut retain = kept.clone();
    for (i, is_kept) in kept.iter().enumerate() {
        if !is_kept {
            // Keep if an adjacent kept version has identical fields.
            let fields_match = |a: &[CommentField], b: &[CommentField]| {
                a.len() == b.len()
                    && a.iter()
                        .zip(b)
                        .all(|(x, y)| x.name == y.name && x.in_type_name == y.in_type_name)
            };
            let adj_match = (i > 0
                && kept[i - 1]
                && fields_match(&versions[i].fields, &versions[i - 1].fields))
                || (i + 1 < kept.len()
                    && kept[i + 1]
                    && fields_match(&versions[i].fields, &versions[i + 1].fields));
            retain[i] = adj_match;
        }
    }

    let mut idx = 0;
    versions.retain(|_| {
        let keep = retain[idx];
        idx += 1;
        keep
    });

    // Clear stale `extends` references to dropped versions.
    let remaining: HashSet<u8> = versions.iter().map(|v| v.version).collect();
    for v in versions {
        if v.extends.is_some_and(|base| !remaining.contains(&base)) {
            v.extends = None;
        }
    }
}

/// Formats a GUID as a lowercase hyphenated string without braces.
